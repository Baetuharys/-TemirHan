#!/usr/bin/env python3
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[1]
out=ROOT/'catalog/generated.md'
rows=[]
for f in sorted((ROOT/'prompts').rglob('*.md')):
 s=f.read_text(encoding='utf-8'); m={}
 for line in s.split('---',2)[1].splitlines():
  if ':' in line:
   k,v=line.split(':',1); m[k.strip()]=v.strip()
 if 'id' in m: rows.append((m.get('type',''),m['id'],m.get('status',''),m.get('summary',''),str(f.relative_to(ROOT))))
text='# Generated Prompt Catalog\n\n> Generated by `scripts/generate_catalog.py`. Do not edit manually.\n\n| Type | ID | Status | Summary | Path |\n|---|---|---|---|---|\n'
text+='\n'.join(f'| {a} | `{b}` | {c} | {d} | `{e}` |' for a,b,c,d,e in rows)+'\n'
out.write_text(text,encoding='utf-8'); print(f'Generated {out} ({len(rows)} items)')
